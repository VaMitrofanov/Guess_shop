/* ─────────────────────────────────────────────────────────────────────────────
   🎁 После «Робуксы поступили» — одна карточка (15.11.2026): спасибо, бонус за
   отзыв (если ещё не получен и заказ с WB) и «купить ещё напрямую». Раньше —
   короткое «спасибо», а отзыв и прямую покупку человек искал сам.
   ───────────────────────────────────────────────────────────────────────── */

export function robuxGotCardText(opts: { reviewPending: boolean; bonus: number; fmt: "html" | "plain" }): string {
  const b = (s: string) => (opts.fmt === "html" ? `<b>${s}</b>` : s);
  return [
    `🙌 ${b("Отлично, робуксы дошли!")} Спасибо, что подтвердили — это очень важно для нас.`,
    ...(opts.reviewPending
      ? ["", `🎁 Оставьте отзыв на Wildberries с текстом и фото — подарим ${b(`+${opts.bonus} R$`)} к следующей прямой покупке. Пришлите скриншот отзыва сюда.`]
      : []),
    "",
    "💎 Захотите ещё — покупка напрямую, без карты WB, по лучшему курсу.",
  ].join("\n");
}
