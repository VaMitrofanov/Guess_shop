/* ─────────────────────────────────────────────────────────────────────────────
   ⏳ Один текст про ожидание Robux в Pending (15.11.2026, владелец: «чтобы
   человек разделял: это не мы, а механика внутри игры»).

   Подставляется везде, где покупателю говорим про срок: ответ «где робуксы»,
   сообщение о выкупе (боты и TWA), FAQ, чат WB, автоответ и ИИ поддержки.
   Ориентир «обычно 5–7 дней» — да; дат, таймеров и «осталось N дней» — нет.
   ───────────────────────────────────────────────────────────────────────── */

export type RobuxWaitVoice = "ty" | "vy";

export function robuxWaitText(voice: RobuxWaitVoice): string {
  const acc = voice === "ty" ? "твой" : "ваш";
  return (
    "Обычно Roblox переводит их на баланс за 5–7 дней. Сейчас по всему рынку у части покупателей бывают задержки: " +
    `Roblox меняет правила переводов внутри игры. От нас это не зависит — свои робуксы мы уже отправили на ${acc} аккаунт.`
  );
}

/**
 * «Выкупили давно, а робуксов нет» — один текст для поддержки (15.11.2026,
 * владелец: «заебался писать про задержки»). Им отвечает бизнес-бот на «где мои
 * робуксы» по выкупленному заказу, и он же лежит быстрым ответом `/задержка`.
 */
export function robuxDelaySupportText(): string {
  return (
    "Понимаем, ждать неприятно 🙏 С нашей стороны заказ выполнен: геймпасс выкуплен, робуксы сейчас в статусе ожидания (Pending).\n\n" +
    robuxWaitText("vy") + "\n\n" +
    "Как проверить: roblox.com → значок Robux → «Мои транзакции» → строка «Робуксы в ожидании» (Pending Robux). Если там есть сумма — всё в порядке: Roblox сам переведёт её на баланс, ничего делать не нужно.\n\n" +
    "Ускорить это не можем ни мы, ни поддержка Roblox, но робуксы никуда не пропадут."
  );
}
