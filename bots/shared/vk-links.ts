/* ─────────────────────────────────────────────────────────────────────────────
   Ссылка на покупателя из ВК — для админов.

   До 11.11.2026 карточки и ТВА вели на `vk.com/id…` или `vk.com/im?sel=…`:
   это профиль или диалог ЛИЧНОГО аккаунта менеджера. Ответить оттуда — значит
   написать покупателю от себя, а не от сообщества, и мимо истории, меток и
   паузы бота. Диалог сообщества — `vk.com/gim<сообщество>?sel=<покупатель>`
   (на телефоне открывается в m.vk.com как «Сообщения сообщества»).

   Исключение — покупатель, недостижимый для сообщества (VK 901): ему пишут
   только с личного, и ТВА ведёт на профиль намеренно.

   Модуль чистый, без env: его берёт и клиентский код ТВА, а id сообщества —
   публичный (vk.me/club237309399 есть на сайте).
   ───────────────────────────────────────────────────────────────────────── */

export const VK_COMMUNITY_ID = 237309399;

/** Диалог с покупателем в «Сообщениях» сообщества. */
export function vkCommunityDialogUrl(vkId: string | number): string {
  return `https://vk.com/gim${VK_COMMUNITY_ID}?sel=${vkId}`;
}

/** `<a>` на диалог сообщества для HTML-карточек Telegram. `label` — уже экранирован. */
export function vkDialogLink(vkId: string | number, label: string): string {
  return `<a href="${vkCommunityDialogUrl(vkId)}">${label}</a>`;
}
