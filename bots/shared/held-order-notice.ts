/* ─────────────────────────────────────────────────────────────────────────────
   Пасс или ключ пришёл на ЗАМОРОЖЕННЫЙ заказ (27.11.2026, кейс 8L3JCD5).

   Заморозка запрещает выкуп, а не приём пасса. Раньше ключ на такой заказ
   пропадал: бот искал «заказ, который ждёт геймпасс» без замороженных и
   отвечал «такого заказа нет», а кнопка ключа в админке отбивалась «заказ
   заморожен». Человек 4 часа делал ключ на планшете ребёнка — и тишина.

   Правило: пасс/ключ принимаем всегда, заказ остаётся замороженным (очереди
   выкупа фильтруют `heldAt` сами), а покупателю честно говорим, почему выкуп
   не начнётся сразу. Плохой отзыв гейт снимает сам, как только отзыв исправлен
   или удалён (`wb-delivery-sync`), поэтому просить об этом не нужно — и нельзя:
   правила WB запрещают выпрашивать оценку.
   ───────────────────────────────────────────────────────────────────────── */

export interface HeldOrderLike {
  heldAt?: Date | string | null;
  heldReason?: string | null;
}

export function isOrderHeld(order: HeldOrderLike | null | undefined): boolean {
  return Boolean(order?.heldAt);
}

/** Заморозка гейта по плохому отзыву WB (`buyout-gate.ts`). */
export function isBadReviewHold(reason: string | null | undefined): boolean {
  return /плох\S* отзыв/i.test(reason ?? "");
}

/**
 * Текст покупателю: пасс принят, выкуп ждёт проверки. Без HTML — годится и
 * для ВК, и для Telegram. Внутреннюю причину дословно не показываем.
 */
export function heldOrderBuyerText(reason: string | null | undefined, wbCode: string): string {
  const why = isBadReviewHold(reason)
    ? "На этот заказ на Wildberries оставлен отзыв с низкой оценкой — такие заказы мы проверяем вручную, прежде чем выкупать."
    : "Заказ сейчас на ручной проверке у менеджера.";
  return (
    `✅ Геймпасс получили и сохранили — заново делать ничего не нужно.\n\n` +
    `⏸ ${why} Как только проверим, выкупим и пришлём уведомление сюда.\n\n` +
    `Если есть вопрос — напишите прямо в этот чат, менеджер ответит.\n\n` +
    `Код ВБ: ${wbCode}`
  );
}

/** Строка в карточку админам: пасс есть, но выкуп всё ещё заблокирован. */
export function heldOrderAdminLine(reason: string | null | undefined): string {
  return `❄️ Заказ ЗАМОРОЖЕН (${reason ?? "причина не указана"}) — пасс принят, в очередь выкупа не встанет до разморозки`;
}
