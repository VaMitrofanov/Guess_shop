/* ─────────────────────────────────────────────────────────────────────────────
   🚚 «Где курьер?» в чате WB (15.11.2026, владелец: «автоответы тем, кто
   спрашивает про курьера — его не было и не будет, в карточке всё написано»).

   Пока доставка не закрыта (кода доставки у нас нет), вопрос про курьера,
   доставку, ПВЗ или «когда привезут» получает автоответ: курьера не будет,
   выдача онлайн в этом чате, пришлите код доставки. Не чаще раза в 6 часов на
   чат; на первый ответ админам увед не шлём — спросит снова, увед придёт.
   Выключатель — `WB_CHAT_COURIER_REPLY=off`.
   ───────────────────────────────────────────────────────────────────────── */

const COURIER_RE = /(курьер|доставк|достав(ят|ите|ят ли)|привез|привоз|прийдет|придет|придёт|когда (будет|ждать|получу)|где (мой |наш )?(заказ|товар|посылк)|пвз|пункт[а-я]* выдачи|отслеж|отслед|трек[- ]?номер|самовывоз|адрес доставки)/i;

export function isCourierQuestion(text: string): boolean {
  const value = text.trim();
  if (!value || value.length > 400) return false;
  // Сообщение с самим кодом (5–7 цифр) — это ответ, а не вопрос.
  if (/\d[\d\s]{4,8}\d/.test(value)) return false;
  return COURIER_RE.test(value);
}

export function courierReplyText(): string {
  return [
    "Здравствуйте! Курьера не будет — товар цифровой, выдача проходит онлайн, прямо в этом чате (так указано в карточке товара).",
    "Чтобы получить заказ, пришлите сюда код доставки — это 5-7 цифр в разделе «Доставки» приложения Wildberries, рядом с QR-кодом.",
    "Отправьте его ТЕКСТОМ, как в приложении: 111 111 или 111111. Сразу после этого пришлём инструкцию.",
  ].join("\n");
}

/** Окно «не чаще раза на чат». */
export const COURIER_REPLY_WINDOW_MS = 6 * 60 * 60_000;
