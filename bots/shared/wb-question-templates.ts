/** Тема-уточнение гасит общую: «сколько дней можно не активировать» — про
 *  срок годности, а не про то, сколько ждать робуксы. */
const SUPPRESS: Partial<Record<QuestionTopic, QuestionTopic[]>> = {
  SHELF_LIFE: ["WAIT_TIME"],
  PASS_READY: ["GAMEPASS_OR_CODE"],
  PASS_PRICE: ["GAMEPASS_OR_CODE"],
};

/** Сколько тем максимум склеиваем в один ответ. */
const MAX_TOPICS = 2;

export function classifyQuestion(input: {
  text: string | null | undefined;
  nmId?: number | null;
  productName?: string | null;
}): QuestionReply | null {
  const raw = (input.text ?? "").trim();
  if (raw.length < 3) return null;
  const text = normalizeQuestion(raw);
  const ctx = { kind: cardKindOf(input.nmId), amount: denominationOf(input.productName) };
  const hits = RULES.filter((rule) => {
    if (ctx.kind === "code" && ["PASS_PRICE", "PASS_READY", "PASS_FREE", "PLACE_PRIVATE"].includes(rule.topic)) return false;
    return rule.re.test(text);
  });
  if (hits.length === 0) return null;
  const found = new Set(hits.filter((h) => h.action === "answer").map((h) => h.topic));
  const muted = new Set([...found].flatMap((t) => SUPPRESS[t] ?? []));
  const answers = [...found].filter((t) => !muted.has(t));
  const first = hits[0];
  if (first.action !== "answer") {
    // Черновик для человека — шаблон этой темы; админ правит или шлёт как есть.
    const topics = [first.topic];
    return { topic: first.topic, topics, action: first.action, text: topics.map((t) => templateText(t, ctx)).join("\n\n") };
  }
  const topics = answers.slice(0, MAX_TOPICS);
  return { topic: topics[0], topics, action: "answer", text: topics.map((t) => templateText(t, ctx)).join("\n\n") };
}
