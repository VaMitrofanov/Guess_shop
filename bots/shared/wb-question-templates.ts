/* ─────────────────────────────────────────────────────────────────────────────
   Шаблоны ответов на вопросы к карточкам WB (12.11.2026).

   Разобраны все 298 вопросов с мая по ноябрь: почти все — десяток одних и тех
   же тем («сколько ждать», «где чат», «100 R$ в подарок», код получения прямо
   в вопросе). Вопросы на WB анонимные и публичные: ответ видят все, кто
   смотрит карточку, а кто спросил — неизвестно. Отсюда правила текстов:
   • никаких ссылок, сайтов, ВК/ТГ — WB за них снимает ответы и штрафует;
   • про конкретный заказ — только «напишите в чат заказа»: здесь его не найти;
   • код получения, присланный в вопрос, не публикуем — вопрос отклоняем
     (`reject`), иначе код увидит любой.

   Модуль чистый: `classifyQuestion` — текст → тема и ответ. Отправкой
   занимается свип, а сомнительное уходит админу на подтверждение.
   ───────────────────────────────────────────────────────────────────────── */

/** Как выдаётся товар карточки. Код — карта 800 R$ с кодом Roblox в чате. */
export type CardKind = "gamepass" | "code";

/** Карточки с выдачей кодом (остальные наши — пополнение через геймпасс). */
export const CODE_CARD_NM_IDS: ReadonlySet<number> = new Set([1447864924]);

export function cardKindOf(nmId: number | null | undefined): CardKind {
  return nmId && CODE_CARD_NM_IDS.has(nmId) ? "code" : "gamepass";
}

/** Номинал из названия карточки («Карта пополнения 500 Robux …»). */
export function denominationOf(productName: string | null | undefined): number | null {
  const m = /(\d{3,4})\s*robux/i.exec(productName ?? "");
  return m ? Number(m[1]) : null;
}

/** Цена пасса для номинала одним пассом (Roblox забирает 30 %). */
export function passPriceFor(amount: number): number {
  return Math.ceil(amount / 0.7);
}

/** Один пасс берём до 1500 R$; больше — несколько пассов, их считает инструкция. */
const SINGLE_PASS_MAX = 1500;

export type QuestionTopic =
  | "CODE_IN_QUESTION"
  | "REFUND"
  | "ORDER_PROBLEM"
  | "DELIVERY_FORMAT"
  | "WHERE_CHAT"
  | "HOW_TO_GET"
  | "GAMEPASS_OR_CODE"
  | "PASS_READY"
  | "PASS_PRICE"
  | "PASS_FREE"
  | "PLACE_PRIVATE"
  | "WAIT_TIME"
  | "BONUS"
  | "COMMISSION"
  | "PASSWORD_SAFETY"
  | "GIFT_OTHER"
  | "CHILD"
  | "DEVICE"
  | "SHELF_LIFE"
  | "MESSENGER"
  | "STOCK_PRICE";

/** `answer` — публикуем; `reject` — отклоняем с текстом (виден только спросившему);
 *  `human` — в админку с черновиком, сами не отвечаем. */
export type QuestionAction = "answer" | "reject" | "human";

export interface QuestionReply {
  /** Главная тема; `topics` — все, из которых собран ответ (не больше двух). */
  topic: QuestionTopic;
  topics: QuestionTopic[];
  action: QuestionAction;
  text: string;
}

const CHAT_HOW = "Откройте заказ в приложении Wildberries → «Задать вопрос продавцу» — откроется чат с нами.";
const ANON = "Здесь вопросы анонимные, и найти ваш заказ по ним мы не можем.";

/** Тексты по темам. Короткие: читают их с телефона, а WB режет длинные. */
export function templateText(topic: QuestionTopic, ctx: { kind: CardKind; amount: number | null }): string {
  const gp = ctx.kind === "gamepass";
  const single = ctx.amount && ctx.amount <= SINGLE_PASS_MAX ? ctx.amount : null;
  switch (topic) {
    case "CODE_IN_QUESTION":
      return `Код получения сюда присылать не нужно — вопросы видят все. ${CHAT_HOW} Отправьте код туда, бот ответит за минуту.`;
    case "REFUND":
      return `Если передумали — оформите возврат в приложении Wildberries в разделе «Покупки». ${ANON} Если что-то не получилось — напишите в чат заказа, разберёмся.`;
    case "ORDER_PROBLEM":
      return `${ANON} Напишите, пожалуйста, в чат заказа — там видно, на каком шаге заказ, и мы поможем. ${CHAT_HOW}`;
    case "DELIVERY_FORMAT":
      return `Товар цифровой: курьер ничего не привозит, а «доставлен» значит, что заказ готов к выдаче в чате. При оформлении выберите доставку курьером (адрес любой), после оплаты пришлите код получения в чат заказа. ${CHAT_HOW}`;
    case "WHERE_CHAT":
      return `${CHAT_HOW} Чат появляется после оплаты, пошаговая картинка — в фото карточки. Туда же присылайте код получения.`;
    case "HOW_TO_GET":
      return gp
        ? `После оплаты пришлите код получения в чат заказа — бот сразу ответит инструкцией. Дальше: ник Roblox → геймпасс по шагам (около 5 минут) → мы его выкупаем. ${CHAT_HOW}`
        : `После оплаты пришлите код получения в чат заказа — в ответ придёт код Roblox и как его активировать. ${CHAT_HOW}`;
    case "GAMEPASS_OR_CODE":
      return gp
        ? "Эта карточка — пополнение через геймпасс: вы создаёте пасс в Roblox по нашей инструкции, мы его выкупаем. Пароль и вход в аккаунт не нужны."
        : "Эта карточка — код Roblox: приходит в чат заказа и активируется на аккаунте сразу.";
    case "PASS_READY":
      return single
        ? `Готовый пасс подойдёт, если он в продаже и цена ${passPriceFor(single)} R$ (для ${single} R$). Бот сам найдёт его по нику; если цена другая — создадите новый по инструкции.`
        : "Готовый пасс подойдёт, если цена совпадает с той, что покажет инструкция. Бот сам найдёт его по нику; если нет — создадите новый.";
    case "PASS_PRICE":
      return single
        ? `Для ${single} R$ поставьте цену пасса ${passPriceFor(single)} R$ — после комиссии Roblox придёт ровно ${single}. Инструкция покажет это же число.`
        : "Цену и количество пассов посчитает инструкция после покупки — для крупных номиналов их несколько.";
    case "PASS_FREE":
      return "Создать геймпасс бесплатно — это делается в самом Roblox за пару минут, инструкция придёт в чат заказа.";
    case "PLACE_PRIVATE":
      return "Плейс может быть закрытым — главное, чтобы пасс был в продаже с нужной ценой.";
    case "WAIT_TIME":
      return gp
        ? "Геймпасс выкупаем в течение дня после того, как вы его создали. Потом Roblox держит робуксы в «Ожидании» (Pending) обычно 5–7 дней — ускорить это нельзя. Видно в Roblox: «Мои транзакции»."
        : "Код приходит в чат заказа сразу после того, как вы пришлёте туда код получения. Робуксы зачисляются сразу после активации.";
    case "BONUS":
      return "К этому заказу 100 R$ не добавляются: придёт ровно купленный номинал. 100 R$ — бонус в нашем магазине, как его получить, расскажем в чате заказа после покупки.";
    case "COMMISSION":
      return ctx.amount
        ? `Комиссию Roblox берём на себя: придёт ровно ${ctx.amount} R$.`
        : "Комиссию Roblox берём на себя: придёт ровно купленный номинал.";
    case "PASSWORD_SAFETY":
      return "Пароль, почта, телефон и паспорт не нужны — только ник Roblox. Пополнение через геймпасс — обычная покупка внутри Roblox, за неё не банят.";
    case "GIFT_OTHER":
      return "Да, можно на другой аккаунт: в инструкции укажите ник того, кому дарите. Несколько заказов — разные ники, у каждого заказа свой код.";
    case "CHILD":
      return "Да, справится: инструкция пошаговая, с картинками. Если что-то не получится — пусть напишет в чат заказа, поможем.";
    case "DEVICE":
      return "Подходит любое устройство: телефон, планшет, ПК. Подписки и возраст аккаунта (Kids, Select) не мешают.";
    case "SHELF_LIFE":
      return "Можно оформить сейчас, а активировать позже. Когда будете готовы — пришлите код получения в чат заказа.";
    case "MESSENGER":
      return `Всё проходит в чате заказа на Wildberries, отдельный мессенджер не нужен. ${CHAT_HOW}`;
    case "STOCK_PRICE":
      return "Цена фиксированная. 300 R$ больше не продаём; есть 500, 800, 1000, 1200 и 2000 R$.";
  }
}

/** Одни и те же слова покупатели пишут десятком способов — приводим к одному. */
export function normalizeQuestion(text: string): string {
  return ` ${text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim()} `
    .replace(/(гейм|гем|геим|гейп|game)\s?-?\s?(пасс?|пас|pass)[а-яa-z0-9]*/g, "геймпасс")
    .replace(/роб[ао]?(кс|кс|акс)[а-яa-z0-9]*|роблокс[а-яa-z0-9]*|робукс[а-яa-z0-9]*|робакс[а-яa-z0-9]*|роблукс[а-яa-z0-9]*|робоксы?/g, "робуксы")
    .replace(/кью ?ар|кюар|qr\s?-?/g, "qr ");
}

/* Правила. Ответ на вопрос «или — или» складывается из двух тем, а не из одной.
   Исключающие (`reject`, `human`) идут первыми и выигрывают целиком: код в
   вопросе и жалобу на заказ шаблоном закрывать нельзя. Короткие слова (вк, тг,
   пк) ищем только целиком: «вк» сидит внутри «доставкой». */
const B = "(?:^|[^а-яa-z0-9])";
const E = "(?=$|[^а-яa-z0-9])";
const word = (alts: string) => new RegExp(`${B}(?:${alts})${E}`);

