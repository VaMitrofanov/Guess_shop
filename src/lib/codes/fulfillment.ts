/**
 * Как выдаём коды: со склада или вручную (15.11.2026).
 *
 * Решение владельца 15.11.2026: продажу открываем, не дожидаясь кодов от
 * поставщика, — оплаченные заказы закрываем ВРУЧНУЮ постфактум
 * (`scripts/codes-issue.mjs` → `/api/internal/codes/issue`).
 *
 * `CODES_BACKORDER=true`: пустой склад не закрывает витрину и оплату, а
 * оплаченный заказ без кода встаёт в «Нужно действие» с пометкой «выдать
 * вручную». Есть код на складе — он, как и раньше, выдаётся сам в момент
 * оплаты. Флаг серверный: включение/выключение — рестарт Web, без пересборки.
 *
 * Пока флаг включён, на витрине нельзя обещать «код за минуту»: интерфейс
 * спрашивает `codesInstantDelivery()` и говорит честное «пришлём после оплаты».
 */

export function codesBackorderEnabled(): boolean {
  return process.env.CODES_BACKORDER === "true";
}

/** Код уходит сам в момент оплаты — только когда ручной режим выключен. */
export function codesInstantDelivery(): boolean {
  return !codesBackorderEnabled();
}

/** Пометка заказа, которому нужен код руками. */
export const MANUAL_ISSUE_REASON = "MANUAL_ISSUE";
