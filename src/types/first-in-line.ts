/* ─────────────────────────────────────────────────────────────────────────────
   Вид блока «Первым делом». Лежит отдельно от `lib/first-in-line.ts`, потому
   что тот помечен `server-only`: обеим главным (сайт и TWA) нужен только тип,
   а не загрузчик с Prisma внутри.
   ───────────────────────────────────────────────────────────────────────── */

export interface FirstInLineOrder {
  id: string;
  wbCode: string;
  robloxUsername: string | null;
  /** Чистые робуксы клиенту. */
  amount: number;
  /** Грязные: столько спишется с выкупного аккаунта. */
  gross: number;
  lane: "WB" | "WB_DBS" | "DIRECT";
  status: string;
  /** С какого момента заказ стоит в очереди. */
  since: string;
  /** Когда заказ создан: от него считается возраст перевыкупа — покупатель
   *  ждёт с первого раза, а не с возврата в очередь. */
  createdAt: string;
  gamepassId: string | null;
  /**
   * Что копировать донору: ID пассов, которые по этому заказу ещё покупать.
   *
   * У обычного заказа это один `gamepassId`, у разбитого — все НЕвыкупленные
   * части в порядке выкупа. Повтор одного пасса не схлопывается: две части на
   * одном пассе — это две покупки с разных доноров, и в списке их должно быть
   * две. Пусто — по заказу копировать нечего (пасс ещё не привязан).
   */
  gamepassIds: string[];
  /**
   * Человеческая часть заметки заказа: зачем он тут, что с ним не так.
   *
   * Машинный аудит (`[РАЗБИВКА …]`, `[ЦЕНА-СТОП …]`) сюда не попадает — на
   * дашборде он занимал бы всю строку и мешал читать то, что написал человек.
   * Правится прямо в блоке, машинные строки при этом сохраняются (`keepTags`).
   */
  note: string | null;
  /** Почему он здесь: перевыкуп, покупатель торопит, подняли руками или это прямой заказ. */
  reason: "rebuy" | "rush" | "pinned" | "direct";
  /**
   * 📣 Покупатель писал за последние 48 ч (поддержка TG/VK, кнопка «Статус»,
   * чат WB) — есть у каждой строки, по которой писали, даже если она в другой
   * группе (перевыкуп тоже может торопить).
   */
  rush?: {
    /** Сколько раз писал — «накал». */
    count: number;
    channels: Array<"TG" | "VK" | "WB">;
    lastAt: string;
    /** Последнее, что написал, одной строкой. */
    quote: string | null;
    /** Как обращался, если цитаты нет: кнопка «Статус» или поддержка без текста. */
    via: "status" | "support" | "chat";
  } | null;
  /** 🔁 Что прислал покупатель — только у `reason: "rebuy"`. */
  rebuyReason?: string | null;
  /** 🔁 Чем заказ закрывали в прошлый раз: «закрыт 2026-10-24 Demid, вручную». */
  rebuyWas?: string | null;
  /** ⚡ Кто поднял и когда — только у поднятых. */
  priorityBy?: string | null;
  priorityAt?: string | null;
}

/** 🛑 Заказ заморожен, потому что покупатель просит отмену — полоса над группами. */
export interface FirstInLineStop {
  id: string;
  wbCode: string;
  amount: number;
  robloxUsername: string | null;
  heldAt: string;
  /** Цитата из причины заморозки. */
  quote: string | null;
}

export interface FirstInLine {
  /**
   * Строки по группам, в порядке групп. В каждой группе — не больше
   * `FIRST_IN_LINE_GROUP_CAP`: «Все» показывает по три, фильтр группы — все
   * загруженные, а за остальным — «Вся очередь».
   */
  rows: FirstInLineOrder[];
  /** Сколько всего таких заказов — строк может быть показано меньше. */
  total: number;
  /** Группы не пересекаются: 🔁 → 📣 → ⚡ → 💳; перевыкуп с ⚡ — в `rebuy`, поднятый прямой — в `pinned`. */
  pinned: number;
  direct: number;
  /** 🔁 Сколько из них — перевыкупы. */
  rebuy?: number;
  /** 📣 Сколько торопят (без перевыкупов — группы не пересекаются). */
  rush?: number;
  /** 🛑 Просьбы об отмене: заказы уже заморожены, выкупать нельзя. */
  stops?: FirstInLineStop[];
  stopTotal?: number;
  /** Сколько всего заказов в очереди выкупа — для «Вся очередь · N →». */
  queueTotal?: number;
  /** Грязные робуксы на все такие заказы: столько нужно прямо сейчас. */
  gross: number;
}
