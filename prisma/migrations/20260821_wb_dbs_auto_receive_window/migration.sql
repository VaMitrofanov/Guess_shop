-- Аддитивно: одна nullable-колонка, существующие строки не переписываются.
-- Для заказов без неё окно считается от `firstSeenAt` (fallback в коде).

-- Момент оформления заказа по версии самого WB (`createdAt` в карточке заказа).
-- `firstSeenAt` для этого не годится: он говорит, когда заказ увидел воркер, и
-- после простоя воркера показал бы многодневный заказ свежим — а на этом стоит
-- решение «закрывать доставку автоматически или звать человека».
ALTER TABLE "WbMarketplaceOrder" ADD COLUMN IF NOT EXISTS "wbCreatedAt" TIMESTAMP(3);
