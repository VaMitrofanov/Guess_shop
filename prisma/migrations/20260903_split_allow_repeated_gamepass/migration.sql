-- Один и тот же геймпасс может закрывать несколько частей одного заказа.
--
-- Уникальность (orderId, gamepassId) стояла из осторожности: два одинаковых
-- пасса на одном донорском аккаунте дали бы AlreadyOwned на второй покупке.
-- Но части разбитого заказа и так выкупаются с РАЗНЫХ доноров (в очереди
-- аккаунты по 2-3 тысячи робуксов), а у покупателя сплошь и рядом выставлен
-- один пасс на 1000 при заказе на 2000 — и такой заказ было не разбить вовсе.
--
-- Инвариант суммы частей и проверка цены каждой части остаются на месте:
-- повторы обязаны иметь одинаковый номинал, это проверяется в коде.
DROP INDEX IF EXISTS "WbOrderGamepass_orderId_gamepassId_key";
