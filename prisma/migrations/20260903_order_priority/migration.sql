-- Ручной приоритет заказа: «этот выкупать первым».
--
-- Очередь выкупа отсортирована по возрасту (`pendingAt asc`), и это правильный
-- порядок по умолчанию. Но у владельца регулярно есть заказ, который надо
-- закрыть вне очереди — доплата, спор на WB, обещанный срок, — и до сих пор
-- единственным способом было держать его в голове и искать по коду в ленте.
--
-- Признак поверх статуса, как и заморозка: заказ остаётся ровно там, где был,
-- и меняется только его место в сортировке. `priorityAt` — момент нажатия,
-- поэтому у нескольких поднятых наверху окажется поднятый последним.
--
-- ВАЖНО: сортировка обязана быть `DESC NULLS LAST` — в Postgres у DESC по
-- умолчанию NULLS FIRST, и без явного NULLS LAST наверх уехали бы все
-- НЕприоритетные заказы.
ALTER TABLE "WbOrder" ADD COLUMN IF NOT EXISTS "priorityAt" TIMESTAMP(3);
ALTER TABLE "WbOrder" ADD COLUMN IF NOT EXISTS "priorityBy" TEXT;

-- Индекс ровно тот, что объявлен в schema.prisma: частичный (`WHERE NOT NULL`)
-- был бы уместнее по данным, но Prisma их не описывает, и схема разошлась бы
-- с базой на первом же `migrate diff`.
CREATE INDEX IF NOT EXISTS "WbOrder_priorityAt_idx" ON "WbOrder" ("priorityAt" DESC);
